// Caller first validates the supported image. The existing line-based file is
// Latin-1: reject unrepresentable/control units rather than silently truncate.
// That file policy is not a restriction on the native UTF-16 vocabulary.
template <class Read> bool readNameFragments(std::uintptr_t module, std::vector<std::string> &output, Read read) {
    output.clear();
    std::vector<std::string> result;
    result.reserve(NAME_LITERALS.size());
    for (const auto literal : NAME_LITERALS) {
        std::array<char16_t, 7> text{};
        if (!literal.units || literal.units > 6 ||
            !readField(module, literal.rva, text.data(), (literal.units + 1) * sizeof(char16_t), read) ||
            text[literal.units])
            return false;
        std::string fragment;
        fragment.reserve(literal.units);
        for (unsigned i = 0; i < literal.units; ++i) {
            const auto unit = text[i];
            if (!unit || unit == u'\n' || unit == u'\r' || unit > 255)
                return false;
            fragment.push_back(static_cast<char>(unit));
        }
        result.push_back(std::move(fragment));
    }
    output = std::move(result);
    return true;
}
